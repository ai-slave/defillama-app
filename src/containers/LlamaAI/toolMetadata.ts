export const getToolLabel = (name: string | undefined | null): string =>
	(name ? getOwnRegistryValue(TOOL_LABELS, name) : undefined) ??
	(name ?? 'Tool')
		.split('_')
		.map((word) => (word ? word.charAt(0).toUpperCase() + word.slice(1) : word))
		.join(' ')

